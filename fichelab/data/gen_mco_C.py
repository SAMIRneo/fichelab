def BL(intro, eq, leg, grille, liste, etapes, attention, exemples):
    return [
        bloc("L'idée en une phrase", texte=intro, type="intro"),
        bloc("La règle à connaître", eq=eq, leg=leg, type="formule"),
        bloc("Tableau de synthèse", items=grille, type="grille"),
        bloc("À retenir", items=liste, type="liste"),
        bloc("Méthode pas à pas", items=etapes, type="etapes"),
        bloc("Pièges fréquents", items=attention, type="attention"),
        bloc("En chiffres et en exemples", items=exemples, type="exemples"),
    ]


def dg(titre, colonnes, lignes):
    return diag(titre, svg_grille(titre, colonnes, lignes))


def df(titre, etapes):
    return diag(titre, svg_flux(titre, etapes))


def de(titre, etapes):
    return diag(titre, svg_etapes(titre, etapes))


def dc(titre, gauche, droite):
    return diag(titre, svg_compare(titre, gauche, droite))


