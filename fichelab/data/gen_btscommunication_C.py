def make(code, titre, mat, ans, notions, points, qs, gcols, grows,
         etapes, attention, exemples, d1, d2, d3, gauche, droite):
    """Fiche complete : 7 blocs dans l'ordre strict + 3 diagrammes."""
    blocs = [
        bloc("L'idee en une phrase", type="intro", texte=points[0]),
        bloc("La formule a connaitre", type="formule", eq=points[1], leg=points[2]),
        bloc("Tableau de reperes", type="grille", items=grows),
        bloc("A retenir sur le chapitre", type="liste", items=points[3:8]),
        bloc("Methode, etape par etape", type="etapes", items=etapes),
        bloc("Pieges frequents", type="attention", items=attention),
        bloc("En chiffres (a savoir refaire)", type="exemples", items=exemples),
    ]
    schemas = [
        diag("1 - " + d1, svg_grille(d1, gcols, grows)),
        diag("2 - " + d2, svg_etapes(d2, etapes)),
        diag("3 - " + d3, svg_compare(d3, gauche, droite)),
    ]
    return fiche(FIL, ans, mat, "Chapitre %s - %s" % (code, titre),
                 REF + " - " + notions, points, qs, blocs, schemas)


