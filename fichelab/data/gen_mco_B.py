def _intro(t, x):
    return {"type": "intro", "titre": t, "texte": x}


def _formule(t, eq, leg):
    return {"type": "formule", "titre": t, "eq": eq, "leg": leg}


def _items(typ):
    def make(t, items):
        return {"type": typ, "titre": t, "items": list(items)}
    return make


_grille = _items("grille")
_liste = _items("liste")
_etapes = _items("etapes")
_attention = _items("attention")
_exemples = _items("exemples")


def B(i, f, g, l, e, a, x):
    """i=(titre,texte) · f=(titre,eq,leg) · autres=(titre,[items])."""
    return [_intro(*i), _formule(*f), _grille(*g), _liste(*l),
            _etapes(*e), _attention(*a), _exemples(*x)]


def mk(ans, mat, titre, source, points, questions, affichage, schemas):
    return fiche(["bts-mco"], ans, mat, titre, source, points, questions,
                 affichage, schemas)


