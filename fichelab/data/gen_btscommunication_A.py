FIL = ["bts-communication"]


def make(ans, mat, code, titre, notions, points, qs, intro, eq, leg,
         gcols, grows, liste, etapes, attention, exemples,
         d1, d2, d2steps, d3, gauche, droite):
    """Construit une fiche complete : 7 blocs stricts + 3 diagrammes diag()."""
    blocs = [
        bloc("L'idee en une phrase", type="intro", texte=intro),
        bloc("La formule a connaitre", type="formule", eq=eq, leg=leg),
        bloc("Tableau de repères", type="grille", items=grows),
        bloc("A retenir sur le chapitre", type="liste", items=liste),
        bloc("Methode, etape par etape", type="etapes", items=etapes),
        bloc("Pieges frequents", type="attention", items=attention),
        bloc("En chiffres (a savoir refaire)", type="exemples", items=exemples),
    ]
    schemas = [
        diag("1 · " + d1, svg_grille(d1, gcols, grows)),
        diag("2 · " + d2, svg_etapes(d2, d2steps)),
        diag("3 · " + d3, svg_compare(d3, gauche, droite)),
    ]
    return fiche(FIL, ans, mat, "Chapitre %s · %s" % (code, titre),
                 REF + " · " + notions, points, qs, blocs, schemas)


