def mk(annees, matiere, titre, source, points, questions, B, schemas):
    """Assemble une fiche prototype : 7 blocs dans l'ordre strict imposé."""
    aff = [
        bloc("L'idée en une phrase", type="intro", texte=B["intro"]),
        bloc("La formule ou le principe à connaître", type="formule",
             eq=B["formule"][0], leg=B["formule"][1]),
        bloc("Tableau de synthèse", type="grille", items=B["grille"]),
        bloc("À retenir", type="liste", items=B["liste"]),
        bloc("Méthode, étape par étape", type="etapes", items=B["etapes"]),
        bloc("Pièges fréquents", type="attention", items=B["attention"]),
        bloc("En chiffres et exemples", type="exemples", items=B["exemples"]),
    ]
    return fiche(FIL, annees, matiere, titre, source, points, questions, aff, schemas)


