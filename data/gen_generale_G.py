def make(titre, mat, ans, pts, qs, blocs, diags, src=""):
    aff = [
        bloc("L'idee en une phrase", texte=blocs[0], type="intro"),
        bloc("Le principe a connaitre", eq=blocs[1][0], leg=blocs[1][1], type="formule"),
        bloc("Tableau de synthese", items=blocs[2], type="grille"),
        bloc("A retenir", items=blocs[3], type="liste"),
        bloc("Methode pas a pas", items=blocs[4], type="etapes"),
        bloc("Pieges frequents", items=blocs[5], type="attention"),
        bloc("Exemples et applications", items=blocs[6], type="exemples"),
    ]
    source = SRC + (" · " + src if src else "")
    return fiche(FIL, ans, mat, titre, source, pts, qs, aff, diags)


def schemas(titre, colonnes, lignes, flux, cmp_titre, gauche, droite, surnom="Synthese"):
    """3 schemas : tableau, flux d'algorithme, comparaison (descriptions courtes)."""
