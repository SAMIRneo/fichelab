def D(kind, titre, *args):
    return (kind, titre, args)


def schema_des(diags):
    out = []
    for i, (kind, titre, args) in enumerate(diags, 1):
        if kind == "g":
            if len(args) < 2:
                colonnes = ["Étape", "Contenu"]
                lignes = [["%d" % (j + 1), e] for j, e in enumerate(args[0])]
            else:
                colonnes, lignes = args[0], args[1]
            svg = svg_grille(titre, colonnes, lignes)
        elif kind == "f":
            etapes = args[0]
            if etapes and isinstance(etapes[0], str):
                etapes = [(e, "") for e in etapes]
            svg = svg_flux(titre, etapes)
        elif kind == "e":
            svg = svg_etapes(titre, args[0])
        else:
            svg = svg_compare(titre, args[0], args[1])
        out.append(diag("%d · %s" % (i, titre), svg))
    return out


